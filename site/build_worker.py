"""Build the Cloudflare Worker that serves site/index.html at domaskai.com/projects/tprm.

The Worker answers only /projects/tprm and /projects/tprm/; any other path it sees is passed
through to the origin unchanged. The page's one inline script is allowed by its SHA-256 hash
in the Content-Security-Policy, so no other script can run, and nothing loads from elsewhere.

    python site/build_worker.py            -> writes site/dist/worker.js (git-ignored)
"""
import base64
import hashlib
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent


def build() -> str:
    html = (HERE / "index.html").read_text(encoding="utf-8")
    scripts = re.findall(r"<script>(.*?)</script>", html, flags=re.S)
    if len(scripts) != 1:
        raise SystemExit(f"expected exactly one inline script, found {len(scripts)}")
    script_hash = base64.b64encode(hashlib.sha256(scripts[0].encode("utf-8")).digest()).decode()
    csp = ("default-src 'none'; style-src 'unsafe-inline'; "
           f"script-src 'sha256-{script_hash}'; img-src data:; base-uri 'none'; form-action 'none'; frame-ancestors 'none'")
    headers = {
        "content-type": "text/html; charset=utf-8",
        "content-security-policy": csp,
        "x-content-type-options": "nosniff",
        "referrer-policy": "strict-origin-when-cross-origin",
        "permissions-policy": "camera=(), microphone=(), geolocation=(), interest-cohort=()",
        "cache-control": "public, max-age=300",
    }
    return f"""// Generated by site/build_worker.py from site/index.html. Do not edit by hand.
const HTML = {json.dumps(html)};
const HEADERS = {json.dumps(headers)};
export default {{
  async fetch(request) {{
    const path = new URL(request.url).pathname;
    if (path === "/projects/tprm" || path === "/projects/tprm/") {{
      if (request.method !== "GET" && request.method !== "HEAD") {{
        return new Response("Method not allowed", {{ status: 405, headers: {{ allow: "GET, HEAD" }} }});
      }}
      return new Response(request.method === "HEAD" ? null : HTML, {{ headers: HEADERS }});
    }}
    return fetch(request);   // anything else under the route goes to the origin unchanged
  }}
}};
"""


if __name__ == "__main__":
    out = HERE / "dist" / "worker.js"
    out.parent.mkdir(exist_ok=True)
    src = build()
    out.write_text(src, encoding="utf-8")
    print(f"{out} ({len(src)} bytes)")
